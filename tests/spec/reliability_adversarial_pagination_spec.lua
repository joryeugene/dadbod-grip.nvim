-- Independent public callback pagination tests, actual disposable SQLite.
local H = dofile('tests/fixtures/safety_adversarial_harness.lua')
local grip, data, view = require('dadbod-grip'), require('dadbod-grip.data'), require('dadbod-grip.view')
local query, db = require('dadbod-grip.query'), require('dadbod-grip.db')
local function open_last(c)
  c.exec([[CREATE TABLE t(id INTEGER PRIMARY KEY,payload TEXT CHECK(payload<>'bad'));
    INSERT INTO t VALUES(1,'visible'),(2,'visible'),(3,'visible'),(4,'visible'),(5,'visible')]])
  grip.setup({ discovery = false, open_sidebar = false, limit = 2, timeout = 5000 })
  local buf, session = c.open('t')
  session.on_requery(buf, query.set_page(session.query_spec, 3))
  H.eq(session.total_rows, 5); H.eq(session.query_spec.page, 3)
  H.eq(session.state.rows[1][1], '5')
  return buf, session
end
H.test('P01 deleting last-page row recounts and moves to actual previous page', function(c)
  local buf, session = open_last(c)
  session.on_delete(buf, 1); c.action('grid_apply')
  H.eq(c.scalar('SELECT count(*) FROM t'), '4')
  H.eq(session.total_rows, 4); H.eq(session.query_spec.page, 2)
  H.eq(session.state.rows, { { '3', 'visible' }, { '4', 'visible' } })
  assert(session.query_sql:find('OFFSET 2', 1, true), session.query_sql)
end)
H.test('P02 insertion recounts rows while retaining the displayed page and ordering', function(c)
  local buf, session = open_last(c)
  view.apply_edit(buf, data.insert_rows_with_values(session.state, 1, { { id = '6', payload = 'visible' } }))
  c.action('grid_apply')
  H.eq(c.scalar('SELECT count(*) FROM t'), '6')
  H.eq(session.total_rows, 6); H.eq(session.query_spec.page, 3)
  H.eq(session.state.rows, { { '5', 'visible' }, { '6', 'visible' } })
end)
H.test('P03 filtered update removes last matching page then Undo restores its total', function(c)
  local buf, session = open_last(c)
  local spec = query.add_filter(session.query_spec, 'payload = \'visible\'')
  spec = query.toggle_sort(spec, 'id'); spec = query.set_page(spec, 3)
  session.on_requery(buf, spec)
  c.edit(buf, session, 1, 'payload', 'hidden'); c.action('grid_apply')
  H.eq(session.total_rows, 4); H.eq(session.query_spec.page, 2)
  H.eq(session.query_spec.filters, spec.filters); H.eq(session.query_spec.sorts, spec.sorts)
  c.action('grid_undo')
  H.eq(session.total_rows, 5); H.eq(session.query_spec.page, 2)
  H.eq(c.scalar("SELECT count(*) FROM t WHERE payload='visible'"), '5')
end)
H.test('P04 deleting the whole table yields zero total and valid first page', function(c)
  local buf, session = open_last(c)
  c.exec('DELETE FROM t WHERE id<5')
  session.on_delete(buf, 1); c.action('grid_apply')
  H.eq(c.scalar('SELECT count(*) FROM t'), '0')
  H.eq(session.total_rows, 0); H.eq(session.query_spec.page, 1)
  H.eq(#session.state.rows, 0)
end)
H.test('P05 failed write preserves staged value, page, count and actual database', function(c)
  local buf, session = open_last(c)
  c.edit(buf, session, 1, 'payload', 'bad'); c.action('grid_apply')
  assert(data.has_changes(session.state), 'failed native CHECK must retain input')
  H.eq(session.total_rows, 5); H.eq(session.query_spec.page, 3)
  H.eq(c.scalar("SELECT payload FROM t WHERE id=5"), 'visible')
end)
H.test('P06 failed post-write COUNT cannot report obsolete total as current', function(c)
  local buf, session = open_last(c)
  local original = db.query
  db.query = function(statement, ...)
    if statement:upper():find('COUNT(*)', 1, true) then return nil, 'controlled COUNT failure' end
    return original(statement, ...)
  end
  session.on_delete(buf, 1)
  local ok, err = pcall(c.action, 'grid_apply')
  db.query = original
  assert(ok, err)
  H.eq(c.scalar('SELECT count(*) FROM t'), '4')
  assert(session.total_rows == nil, 'unavailable count must be unknown, not stale ' .. tostring(session.total_rows))
end)
H.test('P07 an older refresh cannot replace a newer filtered query identity', function(c)
  local buf, session = open_last(c)
  local original, nested = db.query, false
  db.query = function(statement, ...)
    local result, err = original(statement, ...)
    if not nested and not statement:upper():find('COUNT(*)', 1, true) then
      nested = true
      session.on_requery(buf, query.add_filter(session.query_spec, 'id=1'))
    end
    return result, err
  end
  local ok, err = pcall(session.on_refresh, buf)
  db.query = original
  assert(ok, err)
  H.eq(session.total_rows, 1); H.eq(session.query_spec.page, 1)
  H.eq(session.state.rows, { { '1', 'visible' } })
end)
H.finish('reliability_adversarial_pagination_spec')

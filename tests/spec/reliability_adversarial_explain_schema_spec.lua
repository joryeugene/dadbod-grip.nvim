-- Native DuckDB DDL execution and nonexecution controls. SQL is never replayed.
local H=dofile('tests/fixtures/safety_adversarial_harness.lua')
local db,completion=require('dadbod-grip.db'),require('dadbod-grip.completion')
H.test('S10 EXPLAIN ANALYZE DDL completion must not retain old tables',function(c)
 c.url='duckdb:'..c.root..'/explain.duckdb'
 c.exec('CREATE TABLE old_table(id INTEGER)')
 assert(completion.get_schema(c.url).old_table)
 local result,err=db.query('EXPLAIN ANALYZE CREATE TABLE created_table AS SELECT 1 AS id',c.url)
 assert(result,err)
 local oracle=vim.system({'duckdb',c.url:sub(8),'-csv','-c',"SELECT table_name FROM information_schema.tables WHERE table_name='created_table'"},{text=true}):wait()
 assert(oracle.code==0 and oracle.stdout:find('created_table',1,true),'actual EXPLAIN ANALYZE must execute DDL')
 assert(completion.get_schema(c.url).created_table,'successful executed DDL left cached suggestions stale')
end)
H.test('S11 plain EXPLAIN keeps its plan content and does not execute DDL',function(c)
 c.url='duckdb:'..c.root..'/plain.duckdb'
 c.exec('CREATE TABLE old_table(id INTEGER)')
 local before=completion.get_schema(c.url)
 local result,err=db.query('EXPLAIN CREATE TABLE planned_table AS SELECT 2 AS id',c.url)
 assert(result and #result.rows>0,err)
 assert(vim.inspect(result.rows):find('CREATE',1,true),'EXPLAIN plan content lost')
 H.eq(c.scalar("SELECT count(*) FROM information_schema.tables WHERE table_name='planned_table'"),'0')
 H.eq(completion.get_schema(c.url),before,'plain EXPLAIN must not alter schema')
end)
H.finish('reliability_adversarial_explain_schema_spec')

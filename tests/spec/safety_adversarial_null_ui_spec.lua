local H = dofile("tests/fixtures/safety_adversarial_harness.lua")
local data = require("dadbod-grip.data")
local cell_buffer = require("dadbod-grip.cell_buffer")
local eq = H.eq

local function open(c, surface, seed)
  c.exec("CREATE TABLE t(id INTEGER PRIMARY KEY,payload TEXT); INSERT INTO t VALUES(1," .. seed .. ")")
  local grid, session = c.open("t")
  c.focus(grid, session, 1, "payload")
  local buf
  if surface == "float" then
    H.key(grid, "<CR>")
    buf = vim.api.nvim_get_current_buf()
    assert(buf ~= grid, "float did not open")
  else buf = assert(cell_buffer.open(grid)) end
  return grid, session, buf
end
local function save(surface, buf)
  if surface == "float" then H.key(buf, "<CR>") else vim.cmd("write") end
end
local function back(grid)
  local win = vim.fn.bufwinid(grid)
  assert(win ~= -1, "grid window vanished")
  vim.api.nvim_set_current_win(win)
end
for _, surface in ipairs({ "float", "split" }) do
  H.test("UI01 " .. surface .. " empty no-op preserves empty text", function(c)
    local _, session, buf = open(c, surface, "''")
    eq(vim.api.nvim_buf_get_lines(buf, 0, -1, false), { "" })
    save(surface, buf)
    eq(data.effective_value(session.state, 1, "payload"), "")
    eq(data.has_changes(session.state), false)
  end)
  H.test("UI02 " .. surface .. " blank save commits empty text", function(c)
    local grid, _, buf = open(c, surface, "'before'")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "" })
    save(surface, buf)
    back(grid)
    c.action("grid_apply")
    eq(c.scalar("SELECT payload IS NULL FROM t"), "0")
    eq(c.scalar("SELECT length(payload) FROM t"), "0")
  end)
  H.test("UI03 " .. surface .. " legacy sentinel text is saved literally", function(c)
    local grid, _, buf = open(c, surface, "'before'")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "__GRIP_NULL__" })
    save(surface, buf)
    back(grid)
    c.action("grid_apply")
    eq(c.scalar("SELECT payload FROM t"), "__GRIP_NULL__")
  end)
  H.test("UI04 " .. surface .. " cancellation never stages blank text or NULL", function(c)
    local _, session, buf = open(c, surface, "'before'")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "" })
    if surface == "float" then H.key(buf, "q") else vim.cmd("quit!") end
    eq(data.has_changes(session.state), false)
    eq(c.scalar("SELECT payload FROM t"), "before")
  end)
  H.test("UI05 " .. surface .. " NULL no-op stays NULL without staged change", function(c)
    local _, session, buf = open(c, surface, "NULL")
    save(surface, buf)
    eq(data.effective_value(session.state, 1, "payload"), nil)
    eq(data.has_changes(session.state), false)
    eq(c.scalar("SELECT payload IS NULL FROM t"), "1")
  end)
  H.test("UI07 " .. surface .. " old NUL sentinel bytes stage as ordinary text", function(c)
    local _, session, buf = open(c, surface, "'before'")
    local marker = string.char(0) .. "NULL" .. string.char(0)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { marker })
    save(surface, buf)
    eq(data.effective_value(session.state, 1, "payload"), marker)
    eq(c.scalar("SELECT payload FROM t"), "before", "editor save must not write to DB")
  end)
  H.test("UI08 " .. surface .. " explicit empty command changes NULL only after apply", function(c)
    local grid, session, buf = open(c, surface, "NULL")
    assert(vim.api.nvim_buf_get_commands(buf, {}).GripCellEmpty, "missing explicit empty-text workflow")
    vim.cmd("GripCellEmpty")
    eq(data.effective_value(session.state, 1, "payload"), "")
    eq(data.has_changes(session.state), true)
    eq(c.scalar("SELECT payload IS NULL FROM t"), "1", "command stages without a DB write")
    back(grid)
    c.action("grid_apply")
    eq(c.scalar("SELECT payload IS NULL FROM t"), "0")
    eq(c.scalar("SELECT length(payload) FROM t"), "0")
  end)
  H.test("UI09 " .. surface .. " explicit NULL command stages without immediate DB write", function(c)
    local grid, session, buf = open(c, surface, "'before'")
    assert(vim.api.nvim_buf_get_commands(buf, {}).GripCellNull, "missing explicit NULL workflow")
    vim.cmd("GripCellNull")
    eq(data.effective_value(session.state, 1, "payload"), nil)
    eq(data.has_changes(session.state), true)
    eq(c.scalar("SELECT payload FROM t"), "before")
    back(grid)
    c.action("grid_apply")
    eq(c.scalar("SELECT payload IS NULL FROM t"), "1")
  end)
  H.test("UI10 " .. surface .. " stale editor commands cannot stage into a replacement grid", function(c)
    local _, _, buf = open(c, surface, "NULL")
    c.exec("CREATE TABLE other(id INTEGER PRIMARY KEY,payload TEXT); INSERT INTO other VALUES(1,'other')")
    local _, other = c.open("other")
    if vim.api.nvim_buf_is_valid(buf) then
      pcall(vim.api.nvim_buf_call, buf, function() vim.cmd("GripCellEmpty") end)
    end
    eq(data.has_changes(other.state), false, "replacement session must stay clean")
    eq(c.scalar("SELECT payload FROM other"), "other")
    eq(c.scalar("SELECT payload IS NULL FROM t"), "1")
  end)
  for _, action in ipairs({ "save", "empty-command" }) do
    H.test("UI11 " .. surface .. " background refresh cannot retarget stale " .. action, function(c)
      local grid, session, buf = open(c, surface, "NULL")
      c.exec("INSERT INTO t VALUES(2,'other'); DELETE FROM t WHERE id=1")
      session.on_refresh(grid)
      if vim.api.nvim_buf_is_valid(buf) then
        pcall(vim.api.nvim_buf_call, buf, function()
          if action == "empty-command" then vim.cmd("GripCellEmpty")
          else
            vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "wrong-row-if-stale" })
            save(surface, buf)
          end
        end)
      end
      local current = require("dadbod-grip.view")._sessions[grid]
      if current then eq(data.has_changes(current.state), false, "old editor retargeted the new first row") end
      eq(c.scalar("SELECT payload FROM t WHERE id=2"), "other")
    end)
  end
end
H.test("UI06 explicit grid NULL shortcut stays distinct from blank save", function(c)
  c.exec("CREATE TABLE t(id INTEGER PRIMARY KEY,payload TEXT); INSERT INTO t VALUES(1,'before')")
  local grid, session = c.open("t")
  c.focus(grid, session, 1, "payload")
  c.action("grid_null")
  eq(data.effective_value(session.state, 1, "payload"), nil)
  c.action("grid_apply")
  eq(c.scalar("SELECT payload IS NULL FROM t"), "1")
end)
H.finish("safety_adversarial_null_ui_spec")
